#FUNCION SANCION_USUARIO
CREATE DEFINER=`root`@`localhost` FUNCTION `SANCION_USUARIO`(FDEVESPE DATE, FDEVREAL DATE) RETURNS char(15) CHARSET utf8mb4 COLLATE utf8mb4_general_ci
BEGIN

	declare MENSAJE CHAR(15);
    declare RESULTADO INTEGER;
    
        set RESULTADO = datediff(FDEVREAL,FDEVESPE);
    
    if RESULTADO <= 0 then 
		set MENSAJE = 'ACTIVO';
    elseif RESULTADO BETWEEN 1 AND 7  then 
		set MENSAJE = 'ACTIVO';    
	elseif RESULTADO BETWEEN 8 AND 11 then
		set MENSAJE = 'GRAVE';
	else 
		set MENSAJE = 'MUY GRAVE';
	end if;

RETURN MENSAJE;
END

