FROM PRESTAMOS;

/*--------------------------------------------------------------------------------------------------------------------------------*/
#FUNCION MENSAJE_SANCION
CREATE DEFINER=`root`@`localhost` FUNCTION `MENSAJE_SANCION`(NOMBRE VARCHAR(200),APEL1 VARCHAR(200),FINICIO DATE,
    FDEVESPE DATE,FDEVREAL DATE,COD_PRES INT) RETURNS mediumtext CHARSET utf8mb4 COLLATE utf8mb4_general_ci
BEGIN
    DECLARE MENSAJE MEDIUMTEXT;
    DECLARE DIAS_RETRASO INT;
    DECLARE NIVEL_SANCION CHAR(15);

    #Calcular días de retraso
    SET DIAS_RETRASO = DATEDIFF(FDEVREAL, FDEVESPE);

    #Calcular el tipo de sanción llamando a la función anterior
    SET NIVEL_SANCION = SANCION_USUARIO(FDEVESPE, FDEVREAL);

    IF DIAS_RETRASO > 0 THEN
        SET MENSAJE = CONCAT('Estimado usuario ', NOMBRE, ' ', APEL1,', el pasado día ', FINICIO,
            ' realizó un préstamo en nuestra biblioteca con código ', COD_PRES,
            ' y ha superado la fecha de entrega prevista en ', DIAS_RETRASO, 
            ' días,',' por lo que le corresponde una sanción ', NIVEL_SANCION, '.');
 
    END IF;

    RETURN MENSAJE;
END

