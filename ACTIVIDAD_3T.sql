#PROCEDIMIENTO GESTOR
CREATE DEFINER=`root`@`localhost` PROCEDURE `GESTOR`()
BEGIN
    DECLARE COD_PRES INT;
    DECLARE CODUSU INT;
    DECLARE FINICIO DATE;
    DECLARE FDEVESPE DATE;
    DECLARE FDEVREAL DATE;
    DECLARE NOMBRE VARCHAR(200);
    DECLARE APEL1 VARCHAR(200);
    DECLARE NIVEL_SANCION CHAR(15);
    DECLARE MENSAJE MEDIUMTEXT;
    DECLARE DIAS INT;
    
    
	#ACTUALIZO LA TABLA PRESTAMOS CON LAS FUNCIONES
    UPDATE PRESTAMOS P JOIN USUARIOS U ON P.CODUSU = U.COD
    SET P.NIVEL_SANCION = SANCION_USUARIO(P.FDEVESPE, P.FDEVREAL),
        P.MENSAJE = MENSAJE_SANCION(U.NOMBRE,U.APEL1,P.FINICIO,P.FDEVESPE,P.FDEVREAL,P.COD_PRES);
	
    #INSERTAMOS EN LA TABLA SANCIONADOS, SOLO SI LA SANCIÓN ES GRAVE O MUY GRAVE
	INSERT INTO SANCIONADOS (CODUSU, F_PRESTAMO, DIAS_SANCION, MENSAJE) 
    SELECT P.CODUSU,P.FINICIO,DATEDIFF(P.FDEVREAL, P.FDEVESPE),P.MENSAJE FROM PRESTAMOS P
	WHERE P.NIVEL_SANCION IN ('GRAVE', 'MUY GRAVE');
    
    #ACTUALIZO LA COLUMNA CODSAN en PRESTAMOS con la clave de SANCIONADOS
    UPDATE PRESTAMOS P
    JOIN SANCIONADOS S ON P.CODUSU = S.CODUSU AND P.FINICIO = S.F_PRESTAMO
    SET P.CODSAN = S.COD;
    
END

