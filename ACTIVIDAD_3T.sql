CREATE TABLE PRESTAMOS (

	COD_PRES INTEGER PRIMARY KEY auto_increment,
	CODUSU INTEGER NOT NULL,
	CODLIB INTEGER NOT NULL,
    CODSAN INTEGER,
    FINICIO DATE NOT NULL, #TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    FDEVESPE DATE NOT NULL,
    FDEVREAL DATE NOT NULL,
    NIVEL_SANCION CHAR(15),
    MENSAJE MEDIUMTEXT,
    FOREIGN KEY (CODUSU) REFERENCES USUARIOS(COD)
    	ON DELETE CASCADE
		ON UPDATE CASCADE,
    FOREIGN KEY (CODLIB) REFERENCES LIBROS(COD)
